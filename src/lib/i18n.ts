export function feedbackText(language: Language, message: string): string {
  if (message.startsWith('Periodic grant '))
    return (
      text(language, 'Regelmäßige Gutschrift ', 'Periodic grant ') +
      message.slice('Periodic grant '.length)
    );
  if (message.startsWith('Technical checks passed. '))
    return (
      text(language, 'Technische Prüfungen bestanden. ', 'Technical checks passed. ') +
      message.slice('Technical checks passed. '.length)
    );
  if (Object.hasOwn(messages, message)) return t(language, message as MessageKey);
  const known = Object.entries(messages).find(([, english]) => english === message);
  return known && language === 'de' ? known[0] : message;
}
